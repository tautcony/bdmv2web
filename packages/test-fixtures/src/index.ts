/** Fixed octets for cursor boundary/endian tests; expected values are hand-calculated. */
export function buildCursorSample(): Uint8Array {
  return Uint8Array.from([0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09, 0x0a, 0x0b, 0x0c]);
}

export function simulatedBridge<TAction, TEvent>(action: ActionEnvelope<TAction>, event: TEvent): EventEnvelope<TEvent> {
  return {
    sessionId: action.sessionId,
    generation: action.generation,
    sequence: 1,
    responseTo: action.actionId,
    event,
  };
}

